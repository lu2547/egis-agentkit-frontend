export function fileIconType(path: string): string {
  const name =
    path.replaceAll("\\", "/").split("/").at(-1)?.toLowerCase() || "";
  if (name === "go.mod" || name === "go.sum") return "go";
  if (name === ".env" || name.startsWith(".env.")) return "config";
  const dot = name.lastIndexOf(".");
  return dot < 0 ? "file" : extensions[name.slice(dot + 1)] || "file";
}
export function fileIconUrl(path: string): string {
  return `/file-icons/${fileIconType(path)}.svg`;
}
